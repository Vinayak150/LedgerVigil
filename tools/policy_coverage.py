"""Render docs/POLICY_COVERAGE.md from the installed policy registry (tests/test_policies.py asserts the file equals render()).

Run: python -m tools.policy_coverage > docs/POLICY_COVERAGE.md
"""
from ledgervigil.simulation import policies

# Where each policy's contracted outcomes are exercised (tests/test_policies.py). Hand-maintained alongside the tests.
REACH = {
    'P-BAL-01': ('PASS end to end', 'FAIL isolated (an unbalanced simulated entry cannot come from the production posting rule)'),
    'P-ACC-01': ('PASS end to end', 'FAIL isolated; end to end the kernel precondition INACTIVE_ACCOUNT / ACCOUNT_ROLE_TYPE_MISMATCH refuses first'),
    'P-CUR-01': ('PASS end to end', 'FAIL isolated; end to end CURRENCY_MISMATCH / schema scale checks refuse first'),
    'P-REV-01': ('NOT_APPLICABLE end to end', 'FAIL isolated (RecordSettlement never posts to revenue)'),
    'P-CLR-01': ('PASS end to end', 'FAIL and INSUFFICIENT isolated (kernel totals and loader integrity checks refuse first)'),
    'P-CLR-02': ('PASS and FAIL end to end', '—'),
    'P-APP-01': ('NOT_APPLICABLE end to end', 'application changes fail closed (MissingFact), isolated'),
    'P-DUP-01': ('PASS end to end', 'FAIL isolated; end to end DUPLICATE_SETTLEMENT / ITEM_ALREADY_SETTLED preconditions refuse first'),
    'P-FEE-01': ('PASS, FAIL and NOT_APPLICABLE end to end', 'INSUFFICIENT isolated (drafts must cite an existing statement)'),
    'P-PER-01': ('PASS end to end', 'FAIL isolated; end to end PERIOD_CLOSED refuses first; a missing period fails closed'),
    'P-EVD-01': ('INSUFFICIENT end to end (all evidence is SYNTHETIC)', 'PASS only isolated, on an in-memory copy; stored provenance never relabeled'),
    'P-SUB-01': ('NOT_APPLICABLE end to end', 'AR touched fails closed (MissingFact), isolated'),
    'P-SNP-01': ('NOT_APPLICABLE end to end (NATIVE)', 'PASS and INSUFFICIENT isolated; provider simulation is CAPABILITY_UNAVAILABLE'),
    'P-AUT-01': ('not evaluated in simulation (contract)', 'deferred to approval and execution, which are not built'),
    'P-STL-01': ('PASS and FAIL (fee, net, items) end to end', 'INSUFFICIENT isolated (drafts must cite an existing statement)'),
}


def _cell(text):
    return str(text).replace('|', '\\|').replace('\n', ' ')


def render() -> str:
    lines = [f'# Policy coverage: {policies.POLICY_SET} for native RecordSettlement', '',
             f'Generated by `tools/policy_coverage.py` from the installed registry `{policies.POLICY_SET}`; '
             'the test suite asserts this file equals the generated text. The registry content hash is pinned in every new '
             'simulation bundle (`versions.policy_registry`) and is not repeated here, because this file is not part of the registry.', '',
             'Permitted outcomes are the Stage 2A §6.2 columns (P-STL-01: §19.3). An outcome outside them is refused '
             '(`PolicyContractViolation`, nothing recorded). A required fact that is absent raises `MissingFact` (nothing recorded) '
             'unless the contract permits INSUFFICIENT_EVIDENCE for that condition. Nothing silently becomes PASS or NOT_APPLICABLE.', '',
             '| Policy | Version | Owning section | Stage | Permitted outcomes | Inputs required | Applicability | Implemented behaviour | Exercised end to end | Exercised isolated only |',
             '|---|---|---|---|---|---|---|---|---|---|']
    for row in policies.coverage():
        e2e, iso = REACH[row['policy_id']]
        lines.append('| ' + ' | '.join(_cell(x) for x in (
            f"{row['policy_id']} {row['title']}", row['policy_version'], row['section'], row['stage'], ', '.join(row['permitted']),
            '; '.join(row['inputs']), row['applicability'], row['implemented'], e2e, iso)) + ' |')
    lines += ['', 'Aggregation (ADR-014): any FAIL → BLOCKED_FAIL; else any INSUFFICIENT_EVIDENCE → BLOCKED_INSUFFICIENT (a controller '
              'override would be required; overrides are not built); else CLEAR, which requires at least one PASS. NOT_APPLICABLE is '
              'counted separately and never toward a pass. A CLEAR result reads "verified under profile SP-1, policy set '
              f'{policies.POLICY_SET}", never "compliant". Accounting remains UNREVIEWED.', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    print(render(), end='')
